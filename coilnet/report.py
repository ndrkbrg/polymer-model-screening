"""Tiny helper for writing experiment outputs (JSON, figures, a run log) to ``results/``.

The optional historical multibody diagnostic uses this output helper.
The ``results/`` directory is git-ignored (it is regenerated by running the experiments).
"""

from __future__ import annotations

import datetime
import json
from pathlib import Path

import numpy as np

RESULTS_DIR = Path(__file__).resolve().parent.parent / "work/diagnostics"

__all__ = ["RESULTS_DIR", "ensure", "save_json", "fig_path", "log"]


def ensure():
    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    return RESULTS_DIR


def _default(o):
    if isinstance(o, np.ndarray):
        return o.tolist()
    if isinstance(o, np.integer):
        return int(o)
    if isinstance(o, np.floating):
        return float(o)
    if isinstance(o, np.bool_):
        return bool(o)
    return str(o)


def save_json(name, data):
    ensure()
    path = RESULTS_DIR / f"{name}.json"
    path.write_text(json.dumps(data, indent=2, default=_default))
    log(f"saved {path.name}")
    return path


def fig_path(name):
    ensure()
    return RESULTS_DIR / f"{name}.png"


def log(message):
    ensure()
    stamp = datetime.datetime.now().isoformat(timespec="seconds")
    line = f"[{stamp}] {message}"
    with open(RESULTS_DIR / "run_log.txt", "a", encoding="utf-8") as fh:
        fh.write(line + "\n")
    print(line)
